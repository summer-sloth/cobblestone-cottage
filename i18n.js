function skipLanguageNode(element){return !element||!!element.closest('script,style,noscript,.brand,blockquote,[data-no-translate]');}
function translateTextNode(node){
  if(skipLanguageNode(node.parentElement))return;
  const current=node.nodeValue;
  if(!languageOriginalText.has(node))languageOriginalText.set(node,current);
  if(siteLanguage==='ml'){
    if(!/[\u0D00-\u0D7F]/.test(current))languageOriginalText.set(node,current);
    const value=translateCopy(current);if(value!==current)node.nodeValue=value;
  }else{const original=languageOriginalText.get(node);if(current!==original)node.nodeValue=original;}
}
function translateElementAttributes(element){
  if(skipLanguageNode(element))return;
  let originals=languageOriginalAttributes.get(element);if(!originals){originals={};languageOriginalAttributes.set(element,originals);}
  for(const attr of ['aria-label','title','alt']){
    const value=element.getAttribute(attr);if(!value)continue;
    if(!originals[attr])originals[attr]=value;
    if(siteLanguage==='ml'&&!/[\u0D00-\u0D7F]/.test(value)){originals[attr]=value;const translated=translateCopy(value);if(translated!==value)element.setAttribute(attr,translated);}
    else if(siteLanguage==='en'&&value!==originals[attr])element.setAttribute(attr,originals[attr]);
  }
}
function applyLanguage(root){
  if(root.nodeType===Node.TEXT_NODE){translateTextNode(root);return;}
  if(root.nodeType!==Node.ELEMENT_NODE)return;
  translateElementAttributes(root);
  root.querySelectorAll('[aria-label],[title],[alt]').forEach(translateElementAttributes);
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);let node;while((node=walker.nextNode()))translateTextNode(node);
}
